import { google } from 'googleapis';
import { config } from '../config/index.js';
import { getGoogleAuthClient, isGoogleConfigured } from './googleAuth.js';
import { escapeFormula, AsyncLock } from '../utils/helpers.js';

const EXPECTED_HEADERS = [
  'Year',
  'Month',
  'Name',
  'Email',
  'Phone',
  'Applied Role',
  'Application Date & Time',
  'Resume',
  'Application ID',
  'Application Status'
];

const sheetsLock = new AsyncLock();
let isInitialized = false;

/**
 * Ensure the worksheet 'Applications' exists with the 10 standard columns
 * @param {google.sheets_v4.Sheets} sheets 
 * @param {string} spreadsheetId 
 * @param {string} sheetName 
 */
export async function ensureWorksheetAndHeaders(sheets, spreadsheetId, sheetName) {
  if (isInitialized) return;

  try {
    // 1. Get spreadsheet metadata to check if sheetName exists
    const meta = await sheets.spreadsheets.get({
      spreadsheetId,
      fields: 'sheets.properties'
    });

    const existingSheets = meta.data.sheets || [];
    const targetSheet = existingSheets.find(
      s => s.properties && s.properties.title.toLowerCase() === sheetName.toLowerCase()
    );

    // If worksheet doesn't exist, create it
    if (!targetSheet) {
      console.log(`[GoogleSheets] Worksheet '${sheetName}' does not exist. Creating...`);
      await sheets.spreadsheets.batchUpdate({
        spreadsheetId,
        resource: {
          requests: [
            {
              addSheet: {
                properties: {
                  title: sheetName,
                  gridProperties: {
                    rowCount: 1000,
                    columnCount: EXPECTED_HEADERS.length,
                    frozenRowCount: 1
                  }
                }
              }
            }
          ]
        }
      });
    }

    // 2. Check if Row 1 has headers
    const headerRange = `${sheetName}!A1:J1`;
    const headerRes = await sheets.spreadsheets.values.get({
      spreadsheetId,
      range: headerRange
    });

    const rows = headerRes.data.values || [];
    if (rows.length === 0 || rows[0].length === 0) {
      console.log(`[GoogleSheets] Writing standard headers to '${sheetName}!A1:J1'...`);
      await sheets.spreadsheets.values.update({
        spreadsheetId,
        range: headerRange,
        valueInputOption: 'USER_ENTERED',
        resource: {
          values: [EXPECTED_HEADERS]
        }
      });
    }

    isInitialized = true;
  } catch (err) {
    console.error('[GoogleSheets] Error ensuring worksheet & headers:', err.message);
    throw new Error(`Google Sheets setup error: ${err.message}`);
  }
}

/**
 * Append candidate application row to Google Sheets
 * Columns: [Year, Month, Name, Email, Phone, Applied Role, Date & Time, Resume URL, App ID, Status]
 * @param {Object} data 
 * @returns {Promise<{ success: boolean, updatedRange: string }>}
 */
export async function appendApplicationRow(data) {
  const {
    year,
    month,
    name,
    email,
    phone,
    appliedRole,
    dateTimeFormatted,
    resumeUrl,
    applicationId,
    status = 'New'
  } = data;

  if (!isGoogleConfigured() || !config.google.spreadsheetId) {
    console.warn('[GoogleSheets] Google Sheets not fully configured. Running in simulated mode.');
    return {
      success: true,
      updatedRange: `${config.google.worksheetName}!A2:J2 (simulated)`
    };
  }

  // Acquire mutex lock to ensure sequential, concurrency-safe row appending
  return sheetsLock.acquire(async () => {
    const auth = await getGoogleAuthClient();
    const sheets = google.sheets({ version: 'v4', auth });
    const spreadsheetId = config.google.spreadsheetId;
    const sheetName = config.google.worksheetName || 'Applications';

    // Verify worksheet and header row
    await ensureWorksheetAndHeaders(sheets, spreadsheetId, sheetName);

    // Prepare clickable resume formula safely
    // Note: User inputs are escaped, and resumeUrl is generated by our server
    const clickableResumeCell = resumeUrl 
      ? `=HYPERLINK("${resumeUrl.replace(/"/g, '""')}", "View Resume")`
      : 'No Resume';

    // Sanitize user inputs to prevent formula injection (CWE-1236)
    const rowValues = [
      escapeFormula(year),
      escapeFormula(month),
      escapeFormula(name),
      escapeFormula(email),
      escapeFormula(phone),
      escapeFormula(appliedRole),
      escapeFormula(dateTimeFormatted),
      clickableResumeCell,
      escapeFormula(applicationId),
      escapeFormula(status)
    ];

    try {
      const response = await sheets.spreadsheets.values.append({
        spreadsheetId,
        range: `${sheetName}!A:J`,
        valueInputOption: 'USER_ENTERED',
        insertDataOption: 'INSERT_ROWS',
        resource: {
          values: [rowValues]
        }
      });

      console.log(`[GoogleSheets] Appended application row for ID: ${applicationId} at range: ${response.data.updates?.updatedRange}`);

      return {
        success: true,
        updatedRange: response.data.updates?.updatedRange || ''
      };
    } catch (err) {
      console.error('[GoogleSheets] Failed to append application row:', err.message);
      throw new Error(`Google Sheets append failed: ${err.message}`);
    }
  });
}
